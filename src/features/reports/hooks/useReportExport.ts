import { useRef, useState } from "react";
import jsPDF from "jspdf";
import type { ReportDocument } from "@/api/types/reports.types";
import {
  reportCsv,
  reportRows,
  formatReportRange,
  formatReportDate,
} from "../reports.utils";

export function useReportExport(report?: ReportDocument) {
  const [busy, setBusy] = useState<"pdf" | "csv" | null>(null);
  const [error, setError] = useState("");
  const exporting = useRef(false);
  async function download(action: "pdf" | "csv") {
    if (!report || exporting.current) return;
    exporting.current = true;
    setBusy(action);
    setError("");
    const fileName = `Marikina-Market-${"id" in report ? `Report-${report.id}` : "Preview"}-${report.dateRange.from}-${report.dateRange.to}`;
    try {
      if (action === "csv") {
        const url = URL.createObjectURL(
          new Blob([reportCsv(report)], { type: "text/csv;charset=utf-8;" }),
        );
        const link = document.createElement("a");
        link.href = url;
        link.download = `${fileName}.csv`;
        document.body.appendChild(link);
        try {
          link.click();
        } finally {
          link.remove();
          window.setTimeout(() => URL.revokeObjectURL(url), 1000);
        }
      } else {
        const pdf = new jsPDF();
        pdf.setTextColor(0, 90, 170);
        pdf.setFont("helvetica", "bold");
        pdf.setFontSize(18);
        pdf.text("Marikina Public Market Administration", 18, 24);
        pdf.setFontSize(11);
        pdf.text("Inspection & Enforcement Summary Report", 18, 32);
        pdf.setDrawColor(0, 90, 170);
        pdf.line(18, 38, 192, 38);
        pdf.setTextColor(40, 50, 65);
        pdf.setFont("helvetica", "normal");
        pdf.setFontSize(10);
        pdf.text(`Period: ${formatReportRange(report.dateRange)}`, 18, 49);
        pdf.text(`Report type: ${report.type}`, 18, 57);
        if ("id" in report) {
          pdf.text(
            `Report ID: ${report.id} | Generated: ${formatReportDate(report.dateGenerated)}`,
            18,
            65,
          );
          const name = pdf.splitTextToSize(
            `Generated by: ${report.generatedBy.name}`,
            174,
          ) as string[];
          pdf.text(name.slice(0, 3), 18, 73);
        } else pdf.text("Unsaved preview", 18, 65);
        const top = 98;
        pdf.setFillColor(241, 245, 249);
        pdf.rect(18, top - 6, 174, 10, "F");
        pdf.setFont("helvetica", "bold");
        pdf.text("Summary", 20, top);
        pdf.text("Total Records", 130, top, { align: "right" });
        pdf.text("Penalties (PHP)", 190, top, { align: "right" });
        pdf.setFont("helvetica", "normal");
        reportRows(report).forEach((row, index) => {
          const y = top + (index + 1) * 11;
          pdf.text(row.label.replace("—", "-"), 20, y);
          pdf.text(String(row.totalRecords), 130, y, { align: "right" });
          pdf.text(
            row.assessedPenalties.toLocaleString("en-PH", {
              minimumFractionDigits: 2,
              maximumFractionDigits: 2,
            }),
            190,
            y,
            { align: "right" },
          );
          pdf.setDrawColor(220, 225, 232);
          pdf.line(18, y + 4, 192, y + 4);
        });
        pdf.setFontSize(8);
        pdf.text(
          "Dates are inclusive in Asia/Manila. Saved reports preserve their original totals.",
          18,
          275,
        );
        pdf.save(`${fileName}.pdf`);
      }
    } catch {
      setError(
        `Unable to export the ${action.toUpperCase()} file. Please try again.`,
      );
    } finally {
      exporting.current = false;
      setBusy(null);
    }
  }
  return { busy, error, download };
}
