import {
  RecordsToolbar,
  RecordsFooter,
  RecordsState,
} from "@/components/ui/Records";
import { Dropdown } from "@/components/ui/Dropdown";
import RegistryTable from "@/components/ui/RegistryTable";
import type { ReportHistoryModel } from "../hooks/useReportHistory";
import { REPORT_TYPES } from "../reports.utils";
import ReportHistoryRow from "./ReportHistoryRow";
import styles from "./ReportHistory.module.css";

export default function ReportHistory({
  history,
  onView,
  viewDisabled,
}: {
  history: ReportHistoryModel;
  onView: (id: number) => void;
  viewDisabled: boolean;
}) {
  return (
    <section
      className={styles.panel}
      aria-labelledby="report-history-title"
      aria-busy={history.busy}
    >
      <div className={styles.header}>
        <div className={styles.heading}>
          <p>Report history</p>
          <h2 id="report-history-title">Generated reports</h2>
        </div>
        <div className={styles.controls}>
          <RecordsToolbar
            search={history.search}
            onSearch={history.changeSearch}
            searchLabel="Search reports"
            placeholder="Search reports…"
          >
            <Dropdown
              className={styles.filter}
              ariaLabel="Filter report type"
              triggerLabel={
                history.type === "all" ? "All report types" : history.type
              }
              value={history.type}
              onChange={history.changeType}
              options={[
                { value: "all", label: "All report types" },
                ...REPORT_TYPES.map((type) => ({ value: type, label: type })),
              ]}
            />
          </RecordsToolbar>
        </div>
      </div>
      {history.error ? (
        <RecordsState
          title="History unavailable"
          message={history.error}
          onRetry={history.retry}
        />
      ) : history.loading ? (
        <div className={styles.state} role="status">
          Loading report history…
        </div>
      ) : history.rows.length === 0 ? (
        <RecordsState
          title={
            history.search || history.type !== "all"
              ? "No matching reports"
              : "No reports yet"
          }
          message={
            history.search || history.type !== "all"
              ? "Try another search or report type."
              : "Generate a report to begin your report history."
          }
        />
      ) : (
        <RegistryTable
          ariaLabel="Reports table"
          labelledBy="report-history-title"
          busy={history.busy}
          className={styles.table}
          columns={[
            { label: "Type", className: styles.typeColumn },
            { label: "Date Range", className: styles.rangeColumn },
            { label: "Date Generated", className: styles.dateColumn },
            { label: "Generated By", className: styles.actorColumn },
            { label: "Action", className: styles.actionColumn },
          ]}
        >
          {history.rows.map((report) => (
            <ReportHistoryRow
              key={report.id}
              report={report}
              onView={onView}
              disabled={viewDisabled || history.busy}
            />
          ))}
        </RegistryTable>
      )}
      <RecordsFooter
        page={history.page}
        pageSize={history.pageSize}
        total={history.error ? 0 : history.total}
        totalPages={history.totalPages}
        rowCount={history.error ? 0 : history.rows.length}
        label="reports"
        busy={history.busy}
        onPageChange={history.changePage}
      />
    </section>
  );
}
