import type {
  GenerateReportInput,
  ReportDocument,
  ReportHistoryItem,
  ReportType,
  ReportMetric,
} from "@/api/types/reports.types";

export const REPORT_TYPES: readonly ReportType[] = [
  "Warning",
  "Ticket",
  "Warning & Ticket",
];
export const REPORT_PAGE_SIZE = 10;
export type ReportPreset = "month" | "quarter" | "year";

export function manilaToday(now = new Date()): string {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: "Asia/Manila",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(now);
  const part = (type: string) =>
    parts.find((item) => item.type === type)?.value;
  return `${part("year")}-${part("month")}-${part("day")}`;
}
export function isReportDate(value: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00Z`);
  return (
    Number.isFinite(date.getTime()) && date.toISOString().slice(0, 10) === value
  );
}
export function validateReportRange(
  input: GenerateReportInput,
  today = manilaToday(),
): string {
  if (!isReportDate(input.from) || !isReportDate(input.to))
    return "Choose a valid From and To date.";
  if (input.from > input.to)
    return "The To date must be on or after the From date.";
  if (input.to > today) return "Choose dates on or before today.";
  if (!REPORT_TYPES.includes(input.type)) return "Choose a valid report type.";
  return "";
}
export function reportPreset(preset: ReportPreset, today = manilaToday()) {
  const year = Number(today.slice(0, 4));
  const month = Number(today.slice(5, 7));
  if (preset === "year") return { from: `${year}-01-01`, to: today };
  if (preset === "month") return { from: `${today.slice(0, 7)}-01`, to: today };
  const start = new Date(
    Date.UTC(year, Math.floor((month - 1) / 3) * 3 - 3, 1),
  );
  const end = new Date(
    Date.UTC(start.getUTCFullYear(), start.getUTCMonth() + 3, 0),
  );
  return {
    from: start.toISOString().slice(0, 10),
    to: end.toISOString().slice(0, 10),
  };
}
export function formatReportDate(date: string): string {
  return new Intl.DateTimeFormat("en-US", {
    timeZone: "Asia/Manila",
    month: "short",
    day: "numeric",
    year: "numeric",
  }).format(new Date(date.length === 10 ? `${date}T00:00:00+08:00` : date));
}
export function formatReportRange(range: { from: string; to: string }): string {
  return range.from === range.to
    ? formatReportDate(range.from)
    : `${formatReportDate(range.from)} – ${formatReportDate(range.to)}`;
}
export function reportSummaryRows(
  report: ReportDocument,
): Array<ReportMetric & { label: string }> {
  const rows: Array<ReportMetric & { label: string }> = [];
  if (report.summary.warningsIssued) {
    rows.push({
      label: "Warnings issued",
      ...report.summary.warningsIssued,
    });
  }
  if (report.summary.ticketsIssued) {
    rows.push({
      label: "Tickets issued",
      ...report.summary.ticketsIssued,
    });
  }
  return [
    ...rows,
    { label: "Resolved records", ...report.summary.resolved },
    { label: "Pending records", ...report.summary.pending },
    { label: "Total", ...report.summary.total },
  ];
}
export function filterReports(
  items: ReportHistoryItem[],
  search: string,
  type: ReportType | "all",
): ReportHistoryItem[] {
  const term = search.trim().toLocaleLowerCase();
  return items.filter(
    (item) =>
      (type === "all" || item.type === type) &&
      (!term ||
        [
          String(item.id),
          item.type,
          item.generatedBy.name,
          item.dateRange.from,
          item.dateRange.to,
          formatReportRange(item.dateRange),
          formatReportDate(item.dateGenerated),
        ].some((value) => value.toLocaleLowerCase().includes(term))),
  );
}
export function reportCsv(report: ReportDocument): string {
  const escape = (value: string | number) =>
    `"${String(value)
      .replace(/^[\s]*[=+@-]/, (match) => `'${match}`)
      .replace(/"/g, '""')}"`;
  const rows: Array<Array<string | number>> = [
    ["Report type", report.type],
    ["From", report.dateRange.from],
    ["To", report.dateRange.to],
  ];
  if ("id" in report)
    rows.push(
      ["Report ID", report.id],
      ["Date generated", report.dateGenerated],
      ["Generated by", report.generatedBy.name],
    );
  else rows.push(["Status", "Unsaved preview"]);
  rows.push(
    [],
    ["Summary", "Total Records", "Assessed Penalties (PHP)"],
    ...reportSummaryRows(report).map((row) => [
      row.label,
      row.totalRecords,
      row.assessedPenalties,
    ]),
  );
  return `\uFEFF${rows.map((row) => row.map(escape).join(",")).join("\r\n")}`;
}
